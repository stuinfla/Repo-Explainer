#!/usr/bin/env node
// gen-tools-contract.mjs — regenerate skills/explainmyrepo/TOOLS-CONTRACT.md from the leading `//` header block of every tools/*.mjs.
//
// Usage:  node scripts/gen-tools-contract.mjs            write the file
//         node scripts/gen-tools-contract.mjs --check    exit 1 if the committed file differs
// Deterministic: tools sorted by file name, no date stamp. tests/review-p8-tools-contract.test.mjs runs generate()
// in memory and compares it with the committed file, so a tool header edited without regenerating fails CI.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_REL = 'skills/explainmyrepo/TOOLS-CONTRACT.md';

const INTRO = `# TOOLS CONTRACT — the pipeline's toolbox, from each tool's own header

GENERATED by \`node scripts/gen-tools-contract.mjs\` from the leading \`//\` comment block of every tools/*.mjs. Do not edit by hand: edit the tool's header, then regenerate. A test (tests/review-p8-tools-contract.test.mjs) fails when this file and the headers disagree. Read THIS instead of tool source; open source only if this is ambiguous. For which station runs which tool on which door, see src/stations.mjs and tools/CONTRACT.md.
`;

/** The leading `//` block of a source file (after an optional shebang), with the comment markers removed. */
export function headerOf(source) {
  const lines = source.split('\n');
  let i = 0;
  if (lines[0] && lines[0].startsWith('#!')) i = 1;
  const out = [];
  for (; i < lines.length && lines[i].startsWith('//'); i++) out.push(lines[i].replace(/^\/\/ ?/, '').replace(/\s+$/, ''));
  while (out.length && out[out.length - 1] === '') out.pop();
  return out.join('\n');
}

export function toolFiles(root = ROOT) {
  return fs.readdirSync(path.join(root, 'tools')).filter((f) => f.endsWith('.mjs')).sort();
}

export function generate(root = ROOT) {
  const parts = [INTRO];
  for (const f of toolFiles(root)) {
    const header = headerOf(fs.readFileSync(path.join(root, 'tools', f), 'utf8'));
    if (!header) throw new Error(`tools/${f} has no leading // header block`);
    parts.push(`## tools/${f}\n${header}\n`);
  }
  return parts.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(ROOT, OUT_REL);
  const next = generate();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== next) { console.error(`${OUT_REL} is out of date; run: node scripts/gen-tools-contract.mjs`); process.exit(1); }
  } else {
    fs.writeFileSync(out, next);
    console.error(`wrote ${OUT_REL} (${next.split('\n').length} lines, ${toolFiles().length} tools)`);
  }
}
